SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS ai_visibility_prompts (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  prompt_key VARCHAR(120) NOT NULL UNIQUE,
  prompt_text TEXT NOT NULL,
  query_type VARCHAR(48) NOT NULL,
  category_key VARCHAR(120) NULL,
  context_label VARCHAR(190) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  sort_order INT NOT NULL DEFAULT 100,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_ai_vis_prompt_active (is_active,query_type,sort_order),
  KEY idx_ai_vis_prompt_category (category_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_visibility_runs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  provider VARCHAR(64) NOT NULL,
  model_name VARCHAR(120) NULL,
  run_mode VARCHAR(32) NOT NULL DEFAULT 'manual',
  status VARCHAR(24) NOT NULL DEFAULT 'in_progress',
  started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at DATETIME NULL,
  notes TEXT NULL,
  created_by_user_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_ai_vis_run_provider_date (provider,started_at),
  KEY idx_ai_vis_run_status (status,started_at),
  FOREIGN KEY(created_by_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_visibility_observations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  run_id BIGINT UNSIGNED NOT NULL,
  prompt_id BIGINT UNSIGNED NOT NULL,
  observation_status VARCHAR(24) NOT NULL DEFAULT 'valid',
  answer_date DATETIME NOT NULL,
  mentioned TINYINT(1) NULL,
  cited TINYINT(1) NULL,
  cited_url TEXT NULL,
  source_position INT NULL,
  other_sources_json JSON NULL,
  response_reference TEXT NULL,
  notes TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_ai_vis_run_prompt (run_id,prompt_id),
  KEY idx_ai_vis_obs_prompt_date (prompt_id,answer_date),
  KEY idx_ai_vis_obs_status_date (observation_status,answer_date),
  FOREIGN KEY(run_id) REFERENCES ai_visibility_runs(id) ON DELETE CASCADE,
  FOREIGN KEY(prompt_id) REFERENCES ai_visibility_prompts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

