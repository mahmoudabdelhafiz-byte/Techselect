-- TechSelectAI Evaluation Control Center
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS evaluation_proposals (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  product_id BIGINT UNSIGNED NOT NULL,
  methodology_id BIGINT UNSIGNED NOT NULL,
  base_evaluation_id BIGINT UNSIGNED NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'proposed_change',
  proposed_overall_score DECIMAL(4,2) NULL,
  proposed_confidence_score DECIMAL(4,3) NOT NULL DEFAULT 0,
  proposed_summary TEXT NULL,
  proposed_best_for TEXT NULL,
  proposed_limitations TEXT NULL,
  proposed_dimensions_json JSON NOT NULL,
  material_reasons_json JSON NULL,
  supporting_inputs_json JSON NULL,
  evidence_count INT UNSIGNED NOT NULL DEFAULT 0,
  community_evidence_count INT UNSIGNED NOT NULL DEFAULT 0,
  model_provider VARCHAR(50) NULL,
  model_name VARCHAR(100) NULL,
  generator_version VARCHAR(32) NOT NULL,
  generated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at DATETIME NULL,
  reviewed_by_user_id BIGINT UNSIGNED NULL,
  review_notes TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_eval_proposal_queue(status,generated_at),
  KEY idx_eval_proposal_product(product_id,status,generated_at),
  FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE,
  FOREIGN KEY(methodology_id) REFERENCES evaluation_methodologies(id),
  FOREIGN KEY(base_evaluation_id) REFERENCES product_evaluations(id) ON DELETE SET NULL,
  FOREIGN KEY(reviewed_by_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product_evaluation_history (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  product_id BIGINT UNSIGNED NOT NULL,
  methodology_id BIGINT UNSIGNED NOT NULL,
  evaluation_id BIGINT UNSIGNED NULL,
  proposal_id BIGINT UNSIGNED NULL,
  revision_number INT UNSIGNED NOT NULL,
  overall_score DECIMAL(4,2) NULL,
  confidence_score DECIMAL(4,3) NOT NULL DEFAULT 0,
  status VARCHAR(32) NOT NULL,
  summary TEXT NULL,
  best_for TEXT NULL,
  limitations TEXT NULL,
  dimensions_json JSON NOT NULL,
  evidence_count INT UNSIGNED NOT NULL DEFAULT 0,
  community_evidence_count INT UNSIGNED NOT NULL DEFAULT 0,
  methodology_version VARCHAR(32) NOT NULL,
  change_reason TEXT NULL,
  action_by_user_id BIGINT UNSIGNED NULL,
  recorded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_eval_history_revision(product_id,methodology_id,revision_number),
  KEY idx_eval_history_product(product_id,recorded_at),
  FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE,
  FOREIGN KEY(methodology_id) REFERENCES evaluation_methodologies(id),
  FOREIGN KEY(evaluation_id) REFERENCES product_evaluations(id) ON DELETE SET NULL,
  FOREIGN KEY(proposal_id) REFERENCES evaluation_proposals(id) ON DELETE SET NULL,
  FOREIGN KEY(action_by_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
